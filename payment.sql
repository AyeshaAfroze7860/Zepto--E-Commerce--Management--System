CREATE TABLE PAYMENT(
    PAYMENT_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER,
    PAYMENT_DATE DATE,
    PAYMENT_MODE VARCHAR2(30),
    PAYMENT_AMOUNT NUMBER(10,2),
    PAYMENT_STATUS VARCHAR2(20),
    FOREIGN KEY(ORDER_ID) REFERENCES ORDERS(ORDER_ID)
);
