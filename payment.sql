SELECT PAYMENT_ID,
       ORDER_ID,
       PAYMENT_MODE,
       PAYMENT_AMOUNT,
       PAYMENT_STATUS
FROM PAYMENT
WHERE PAYMENT_STATUS IN ('FAILED','PENDING');

SELECT PAYMENT_MODE,
       COUNT(PAYMENT_ID) AS TOTAL_TRANSACTIONS
FROM PAYMENT
GROUP BY PAYMENT_MODE;

SELECT P.PAYMENT_ID,
       O.ORDER_ID,
       O.ORDER_DATE,
       P.PAYMENT_MODE,
       P.PAYMENT_AMOUNT,
       P.PAYMENT_STATUS
FROM ORDERS O
JOIN PAYMENT P
ON O.ORDER_ID = P.ORDER_ID
ORDER BY O.ORDER_DATE;

SELECT C.CUSTOMER_NAME,
       O.ORDER_ID,
       P.PAYMENT_MODE,
       P.PAYMENT_AMOUNT,
       P.PAYMENT_STATUS
FROM CUSTOMER C
JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN PAYMENT P
ON O.ORDER_ID = P.ORDER_ID
ORDER BY C.CUSTOMER_NAME;